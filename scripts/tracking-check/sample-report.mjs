// Builds the sample report on the Tracking Check landing page by running the real assess() on made-up
// observations for www.example.com. Run `node scripts/tracking-check/sample-report.mjs` after changing the
// assess modules; tests/foundation/tracking-check-sample.test.mjs fails while the committed file is stale.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { assess } from '../../supabase/functions/_shared/tracking-check/assess/index.ts';
import { summarize } from '../../supabase/functions/_shared/tracking-check/report.ts';
import { vendorMatrix } from '../../supabase/functions/_shared/tracking-check/vendor-matrix.ts';

const ORIGIN = 'https://www.example.com';
const OUT = fileURLToPath(new URL('../../src/data/trackingCheckSample.ts', import.meta.url));

const req = (url, type = 'script') => ({ url, type });
const ga = (gcs, path = '/') => req(`https://region1.google-analytics.com/g/collect?v=2&tid=G-SAMPLE123&gcs=${gcs}&dl=${encodeURIComponent(ORIGIN + path)}&en=page_view`, 'xhr');
const st = (state, extra = {}) => ({
  state, method: state === 'none' ? 'not_needed' : 'adapter', status: 200,
  requests: [], cookies: [], storageKeys: [], cspViolations: [], consentCommands: [],
  enhancedConversions: false, challenge: false, error: null, bannerSeen: true, ...extra,
});
const fetchOk = (path) => ({
  requestedUrl: ORIGIN + path, hops: [{ url: ORIGIN + path, status: 200 }], finalUrl: ORIGIN + path,
  finalStatus: 200, paramsLost: [], csp: null, challenge: false, error: null,
});
const page = (path, states) => ({
  path, legacy: false, failed: null, fetch: fetchOk(path),
  browser: { url: ORIGIN + path, cmp: 'cookiebot', states, forms: [] },
});

const GTAG = req('https://www.googletagmanager.com/gtag/js?id=G-SAMPLE123');
const META_JS = req('https://connect.facebook.net/en_US/fbevents.js');
const thanks = `${ORIGIN}/thanks?email=test%40example.org`;
const META_HIT = req(`https://www.facebook.com/tr/?id=1234567890&ev=PageView&dl=${encodeURIComponent(thanks)}`, 'image');
const LIBSYN = req('https://html5-player.libsyn.com/embed/episode/id/123456', 'document');

// Google Analytics fires before the choice without a Consent Mode signal; Meta keeps loading after
// "Reject all"; the thank-you page puts the visitor's email address in the URL Meta receives.
const home = page('/', [
  st('none', { requests: [GTAG, ga('G1--')], cookies: [{ name: '_ga', domain: '.example.com' }, { name: '_ga_SAMPLE123', domain: '.example.com' }] }),
  st('reject', { requests: [META_JS, req('https://www.facebook.com/tr/?id=1234567890&ev=PageView', 'image')], cookies: [{ name: '_fbp', domain: '.example.com' }] }),
  st('accept', { requests: [GTAG, ga('G111'), META_JS] }),
]);
const podcast = page('/podcast', [
  st('none', { requests: [LIBSYN] }),
  st('reject', { requests: [LIBSYN] }),
  st('accept', { requests: [GTAG, ga('G111', '/podcast'), LIBSYN] }),
]);
const thankYou = page('/thanks?email=test@example.org', [
  st('none'),
  st('reject'),
  st('accept', { requests: [GTAG, ga('G111', '/thanks'), META_JS, META_HIT] }),
]);

const POLICY = {
  noGoogleBeforeConsent: true, consentDefaultsDenied: true, ga4RequiresAnalytics: true, adsRequiresMarketing: true,
  enhancedConversionsOff: true, noUnknownVendorsAfterReject: true, expectedIds: ['G-SAMPLE123'],
  manualItems: [{ key: 'reject_equal', label: '"Reject all" is as easy as "Accept all" and no categories are pre-ticked' }],
};

export function buildSample() {
  const target = { role: 'target', origin: ORIGIN, pages: [home, podcast, thankYou] };
  const findings = assess({ mode: 'policy', baseline: null, policy: POLICY, target });
  return { targetUrl: ORIGIN, summary: { ...summarize(findings, 'policy', POLICY), vendors: vendorMatrix(target, findings) }, findings: findings.map((f) => ({ ...f, verifiedAt: null })) };
}

export const render = (sample) => `// Generated by scripts/tracking-check/sample-report.mjs from the real assess() output. Do not edit.
import type { ReportSummary } from '../../supabase/functions/_shared/tracking-check/report.ts';
import type { FindingRow } from '@/hooks/useTrackingCheck';

export const TRACKING_CHECK_SAMPLE: { targetUrl: string; summary: ReportSummary; findings: FindingRow[] } = ${JSON.stringify(sample, null, 2)};
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, render(buildSample()));
  console.log(`Wrote ${OUT}`);
}
