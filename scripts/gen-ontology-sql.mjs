// Generates the SQL that the agent and integration ontologies own: bot_catalog rows, its category
// CHECK, the visitor_type CHECKs and the company_integrations.integration_type CHECK.
//
//   node scripts/gen-ontology-sql.mjs          write a new *_ontology_sync.sql migration if out of sync
//   node scripts/gen-ontology-sql.mjs --check  exit 1 if out of sync (first step of `npm run build`)
//
// Each sync migration is the full state, so the latest one is what the ontology must render to.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BOT_CLASSES, VISITOR_TYPES, botCatalog } from '../supabase/functions/_shared/agent-ontology.ts';
import { integrations } from '../src/ontology/integrations.ts';

export const MIGRATIONS_DIR = fileURLToPath(new URL('../supabase/migrations/', import.meta.url));
const SYNC_SUFFIX = '_ontology_sync.sql';

const lit = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const list = (values) => values.map(lit).join(', ');
const textArray = (values) => `ARRAY[${list(values)}]::text[]`;

/** Integration instance IDs: the allowed company_integrations.integration_type values. */
export const integrationTypes = () =>
  Object.values(integrations).filter((c) => c.kind === 'integration-instance').map((c) => c.id);

function checkConstraint(table, column, values, comment) {
  const name = `${table}_${column}_check`;
  return [
    `ALTER TABLE public.${table} DROP CONSTRAINT IF EXISTS ${name};`,
    `ALTER TABLE public.${table} ADD CONSTRAINT ${name}\n  CHECK (${column} IN (${list(values)}));`,
    `COMMENT ON COLUMN public.${table}.${column} IS\n  ${lit(comment)};`,
  ].join('\n');
}

export function renderOntologySql() {
  const bots = botCatalog();
  const names = list(bots.map((b) => b.slug));
  const rows = bots.map((b, i) =>
    `  (${lit(b.slug)}, ${lit(b.name)}, ${lit(b.category)}, ${textArray(b.uaPatterns)}, ${lit(b.description)}, ${lit(b.vendor)}, ${i + 1}, true)`,
  ).join(',\n');

  return `-- GENERATED by scripts/gen-ontology-sql.mjs from supabase/functions/_shared/agent-ontology.ts
-- and src/ontology/integrations.ts. Do not edit: change the ontology and run the script, which
-- writes a new *_ontology_sync.sql. tests/foundation/ontology-sql.test.mjs fails the build when
-- the latest one is out of sync.

-- ── bot_catalog ──────────────────────────────────────────────────────────────
ALTER TABLE public.bot_catalog DROP CONSTRAINT IF EXISTS bot_catalog_category_check;

-- Rows the ontology no longer has: keep their detections, drop the link.
UPDATE public.bot_detections SET bot_catalog_id = NULL
WHERE bot_catalog_id IN (SELECT id FROM public.bot_catalog WHERE name NOT IN (${names}));
DELETE FROM public.bot_catalog WHERE name NOT IN (${names});

INSERT INTO public.bot_catalog (name, display_name, category, ua_patterns, description, vendor, match_order, is_active)
VALUES
${rows}
ON CONFLICT (name) DO UPDATE SET
  display_name = EXCLUDED.display_name,
  category     = EXCLUDED.category,
  ua_patterns  = EXCLUDED.ua_patterns,
  description  = EXCLUDED.description,
  vendor       = EXCLUDED.vendor,
  match_order  = EXCLUDED.match_order,
  is_active    = EXCLUDED.is_active;

${checkConstraint('bot_catalog', 'category', BOT_CLASSES, 'Agent ontology leaf class under automated_agent. Generated from _shared/agent-ontology.ts.')}

-- ── visitor_type ─────────────────────────────────────────────────────────────
${Object.entries(VISITOR_TYPES).map(([table, map]) =>
  checkConstraint(table, 'visitor_type', Object.keys(map),
    `Maps to agent ontology classes: ${Object.entries(map).map(([v, ids]) => `${v} = ${ids.join(' | ')}`).join('; ')}. Generated from _shared/agent-ontology.ts.`),
).join('\n\n')}

-- ── integration_type ─────────────────────────────────────────────────────────
${checkConstraint('company_integrations', 'integration_type', integrationTypes(), 'Integration ontology instance ID. Generated from src/ontology/integrations.ts.')}
`;
}

const normalise = (s) => s.replace(/\r\n/g, '\n');

/** The latest sync migration: { file, sql } or null. */
export function latestSyncMigration(dir = MIGRATIONS_DIR) {
  const file = readdirSync(dir).filter((f) => f.endsWith(SYNC_SUFFIX)).sort().at(-1);
  return file ? { file, sql: normalise(readFileSync(join(dir, file), 'utf8')) } : null;
}

/** Next migration prefix: after the latest migration and not before today. */
export function nextMigrationPrefix(dir = MIGRATIONS_DIR, today = new Date()) {
  const latest = readdirSync(dir).map((f) => f.match(/^(\d{14})_/)?.[1]).filter(Boolean).sort().at(-1);
  const day = BigInt(`${today.toISOString().slice(0, 10).replace(/-/g, '')}000001`);
  const after = latest ? BigInt(latest) + 1n : 0n;
  return String(after > day ? after : day);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const sql = renderOntologySql();
  const latest = latestSyncMigration();
  if (latest?.sql === sql) {
    console.log(`ontology SQL in sync (${latest.file})`);
  } else if (process.argv.includes('--check')) {
    console.error(`ontology SQL out of sync with ${latest?.file ?? 'no sync migration'}: run node scripts/gen-ontology-sql.mjs`);
    process.exit(1);
  } else {
    const file = `${nextMigrationPrefix()}${SYNC_SUFFIX}`;
    writeFileSync(join(MIGRATIONS_DIR, file), sql);
    console.log(`wrote supabase/migrations/${file}`);
  }
}
